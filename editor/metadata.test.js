'use strict';
const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const os = require('node:os');
const { readDocument, viewMetadata, editMetadata, taxonomy, manageTaxonomy, saveSite } = require('./metadata');
const { readConfig, saveDeployment } = require('./configuration');

test('article fields preserve body and custom folds; taxonomy changes back up versions', async t => {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'moonlit-metadata-'));
  const previous = process.env.MOONLIT_ARTICLE_BACKUPS;
  process.env.MOONLIT_ARTICLE_BACKUPS = path.join(root, 'cloud');
  const project = path.join(root, 'site');
  fs.mkdirSync(path.join(project, 'content/_posts'), { recursive: true });
  fs.writeFileSync(path.join(project, '_config.yml'), '# Keep this comment\ntitle: Example\nsource_dir: content\nurl: https://example.test/\nkeywords: old, site\n');
  const body = '\nHello\n\n<details>\n<summary>Extra notes</summary>\n\nHidden text\n\n</details>\n';
  const text = '---\ntitle: Original\ncategory: Notes\ntags: [old]\nkeywords: old, text\ncustom: keep-me\n---\n' + body;
  const file = path.join(project, 'content/_posts/one.md');
  fs.writeFileSync(file, text);
  t.after(() => {
    if (previous === undefined) delete process.env.MOONLIT_ARTICLE_BACKUPS;
    else process.env.MOONLIT_ARTICLE_BACKUPS = previous;
    fs.rmSync(root, { recursive: true, force: true });
  });
  const edited = editMetadata(text, { title: 'New title', categories: ['Learning'], tags: ['new'], keywords: ['tools','writing'] });
  assert.equal(readDocument(edited.frontMatter + body).body, body);
  assert(edited.frontMatter.includes('custom: keep-me'));
  assert.equal(edited.metadata.title, 'New title');
  assert.deepEqual(edited.metadata.categories, ['Learning']);
  assert.deepEqual(taxonomy(project).keywords, ['old','site','text']);
  const renamed = manageTaxonomy(project, { kind:'tags', action:'rename', name:'old', replacement:'new' });
  assert.equal(renamed.updated, 1);
  assert.deepEqual(viewMetadata(fs.readFileSync(file, 'utf8')).tags, ['new']);
  assert.equal(readDocument(fs.readFileSync(file, 'utf8')).body, body);
  manageTaxonomy(project, { kind:'categories', action:'remove', name:'Notes' });
  assert.deepEqual(viewMetadata(fs.readFileSync(file, 'utf8')).categories, []);
  manageTaxonomy(project, { kind:'keywords', action:'rename', name:'old', replacement:'fresh' });
  assert(readConfig(project).value.keywords.includes('fresh'));
  saveSite(project, { title:'A new site', subtitle:'Subtitle', description:'Description', keywords:'one,two' });
  assert(fs.readFileSync(path.join(project,'_config.yml'),'utf8').includes('# Keep this comment'));
  await saveDeployment(project, { repository:'example/site', branch:'gh-pages', siteUrl:'https://example.github.io/site/', githubPages:true });
  const config = readConfig(project).value;
  assert.equal(config.deploy.repo, 'https://github.com/example/site.git');
  assert.equal(config.root, '/site/');
  assert.equal(config.moonlit.github_pages, true);
  const versions = path.join(root,'cloud/_posts/one/versions');
  assert(fs.readdirSync(versions).length >= 3);
});
