'use strict';
const fs = require('node:fs');
const path = require('node:path');
const languages = require('./languages.json');
const codes = new Set();
const catalogs = {};
for (const language of languages) {
  if (!/^[a-z]{2,3}(?:-[A-Za-z0-9]+)*$/.test(language.code) || codes.has(language.code) || !language.label || !language.htmlLang) throw new Error('Invalid language registry');
  codes.add(language.code);
  if (language.catalog !== null && !/^[A-Za-z0-9_.-]+\.json$/.test(language.catalog)) throw new Error('Invalid translation catalog path');
  catalogs[language.code] = language.catalog === null ? null : JSON.parse(fs.readFileSync(path.join(__dirname,language.catalog),'utf8'));
}
if (!codes.has('en')) throw new Error('English fallback is required');
fs.writeFileSync(path.join(__dirname,'ui-strings.js'), '// Generated by generate-i18n.js from languages.json and translation catalogs.\nwindow.MOONLIT_LANGUAGES = ' + JSON.stringify(languages,null,2) + ';\nwindow.MOONLIT_CATALOGS = ' + JSON.stringify(catalogs,null,2) + ';\nwindow.MOONLIT_STRINGS = window.MOONLIT_CATALOGS.en;\n');
